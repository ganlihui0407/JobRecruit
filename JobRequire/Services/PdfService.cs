        /// <summary>
        /// Generate PDF from HTML content using DinkToPdf (legacy method)
        /// </summary>
        public byte[] GeneratePdfFromHtml(string htmlContent, string title = "Document")
        {
            if (_dinkToPdfFailed)
            {
                _logger.LogDebug("DinkToPdf not available, skipping.");
                return Array.Empty<byte>();
            }

            try
            {
                var globalSettings = new GlobalSettings
                {
                    ColorMode = ColorMode.Color,
                    Orientation = Orientation.Portrait,
                    PaperSize = PaperKind.A4,
                    Margins = new MarginSettings { Top = 10, Bottom = 10, Left = 10, Right = 10 },
                    DocumentTitle = title
                };

                var objectSettings = new ObjectSettings
                {
                    PagesCount = true,
                    HtmlContent = htmlContent,
                    WebSettings = { DefaultEncoding = "utf-8" },
                    HeaderSettings = { FontSize = 9, Right = "Page [page] of [toPage]", Line = false },
                    FooterSettings = { FontSize = 9, Center = "Generated by JobRecruit", Line = false }
                };

                var document = new HtmlToPdfDocument
                {
                    GlobalSettings = globalSettings,
                    Objects = { objectSettings }
                };

                var pdfBytes = _converter.Convert(document);
                _logger.LogInformation("PDF generated successfully with DinkToPdf: {Title}", title);
                return pdfBytes;
            }
            catch (DllNotFoundException ex)
            {
                _dinkToPdfFailed = true;
                _logger.LogWarning(ex, "DinkToPdf native library not found. Will use QuestPDF instead.");
                return Array.Empty<byte>();
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error generating PDF with DinkToPdf: {Title}", title);
                return Array.Empty<byte>();
            }
        }

        /// <summary>
        /// Generate resume PDF for a job seeker using QuestPDF
        /// </summary>
        public async Task<byte[]?> GenerateResumePdfAsync(int jobSeekerProfileId)
        {
            try
            {
                var snapshot = await _resumeService.GetResumeSnapshotAsync(jobSeekerProfileId);
                
                if (snapshot == null)
                {
                    _logger.LogWarning("Resume snapshot not found for profile {ProfileId}", jobSeekerProfileId);
                    return null;
                }

                // Log profile photo info for debugging
                _logger.LogInformation("PDF Generation - ProfilePhoto: '{Photo}', ProfilePhotoBase64 length: {Base64Len}", 
                    snapshot.ProfilePhoto ?? "(null)", 
                    snapshot.ProfilePhotoBase64?.Length ?? 0);

                bool hasContent = !string.IsNullOrEmpty(snapshot.FullName) &&
                    (snapshot.Education?.Count > 0 || 
                     snapshot.Experience?.Count > 0 || 
                     snapshot.Skills?.Count > 0 ||
                     !string.IsNullOrEmpty(snapshot.Summary));

                if (!hasContent)
                {
                    _logger.LogWarning("Resume has no content for profile {ProfileId}", jobSeekerProfileId);
                    return null;
                }

                // Generate PDF using QuestPDF (reliable, no native dependencies)
                var pdfBytes = GenerateResumePdfWithQuestPdf(snapshot);
                
                if (pdfBytes != null && pdfBytes.Length > 0)
                {
                    _logger.LogInformation("PDF generated successfully with QuestPDF for profile {ProfileId}", jobSeekerProfileId);
                    return pdfBytes;
                }

                _logger.LogWarning("PDF generation returned empty result for profile {ProfileId}", jobSeekerProfileId);
                return null;
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error generating resume PDF for profile {ProfileId}", jobSeekerProfileId);
                return null;
            }
        }

        /// <summary>
        /// Generate resume PDF using QuestPDF library
        /// This matches the visual design of the Preview/Print Ready template
        /// </summary>
        private byte[] GenerateResumePdfWithQuestPdf(ResumeSnapshotViewModel snapshot)
        {
            var document = Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(40);
                    page.DefaultTextStyle(x => x.FontSize(10).FontColor(Colors.Grey.Darken3));

                    page.Content().Column(column =>
                    {
                        // Header Section
                        column.Item().BorderBottom(2).BorderColor(Colors.Blue.Medium).PaddingBottom(15).Column(header =>
                        {
                            // Profile Photo (if available)
                            if (!string.IsNullOrEmpty(snapshot.ProfilePhoto))
                            {
                                try
                                {
                                    var photoPath = GetAbsolutePhotoPath(snapshot.ProfilePhoto);
                                    _logger.LogInformation("PDF Photo path: {PhotoPath}, Exists: {Exists}", photoPath, File.Exists(photoPath));
                                    
                                    if (File.Exists(photoPath))
                                    {
                                        // Read image bytes and embed directly
                                        var imageBytes = File.ReadAllBytes(photoPath);
                                        header.Item().AlignCenter().Width(100).Height(100).Image(imageBytes).FitArea();
                                        header.Item().Height(10);
                                        _logger.LogInformation("Successfully embedded profile photo in PDF ({Size} bytes)", imageBytes.Length);
                                    }
                                    else
                                    {
                                        _logger.LogWarning("Profile photo file not found at: {PhotoPath}", photoPath);
                                    }
                                }
                                catch (Exception ex)
                                {
                                    _logger.LogWarning(ex, "Could not load profile photo for PDF: {PhotoPath}", snapshot.ProfilePhoto);
                                }
                            }
                            else
                            {
                                _logger.LogInformation("No profile photo set for this resume");
                            }

                            // Name
                            header.Item().AlignCenter().Text(snapshot.FullName ?? "")
                                .FontSize(24).Bold().FontColor(Colors.Blue.Darken3);

                            // Contact Info
                            header.Item().Height(8);
                            header.Item().AlignCenter().Row(row =>
                            {
                                if (!string.IsNullOrEmpty(snapshot.Email))
                                {
                                    row.AutoItem().Text($"📧 {snapshot.Email}").FontSize(10).FontColor(Colors.Grey.Darken1);
                                    if (!string.IsNullOrEmpty(snapshot.PhoneNumber))
                                        row.AutoItem().PaddingHorizontal(15).Text("|").FontColor(Colors.Grey.Medium);
                                }
                                if (!string.IsNullOrEmpty(snapshot.PhoneNumber))
                                {
                                    row.AutoItem().Text($"📱 {snapshot.PhoneNumber}").FontSize(10).FontColor(Colors.Grey.Darken1);
                                }
                            });
                        });

                        column.Item().Height(20);

                        // Professional Summary
                        if (!string.IsNullOrEmpty(snapshot.Summary))
                        {
                            column.Item().Element(c => RenderSection(c, "📋 Professional Summary", content =>
                            {
                                content.Item().Text(snapshot.Summary).FontSize(10).FontColor(Colors.Grey.Darken2).LineHeight(1.5f);
                            }));
                        }

                        // Work Experience
                        if (snapshot.Experience?.Count > 0)
                        {
                            column.Item().Element(c => RenderSection(c, "💼 Work Experience", content =>
                            {
                                foreach (var exp in snapshot.Experience)
                                {
                                    content.Item().BorderLeft(3).BorderColor(Colors.Blue.Medium).PaddingLeft(10).PaddingBottom(10).Column(item =>
                                    {
                                        item.Item().Row(row =>
                                        {
                                            row.RelativeItem().Column(left =>
                                            {
                                                left.Item().Text(exp.JobTitle ?? "").Bold().FontSize(11).FontColor(Colors.Grey.Darken4);
                                                left.Item().Text(exp.CompanyName ?? "").FontSize(10).FontColor(Colors.Grey.Darken1);
                                            });
                                            row.AutoItem().AlignRight().Background(Colors.Grey.Lighten3).Padding(4)
                                                .Text($"{(exp.StartDate?.ToString("MMM yyyy") ?? "N/A")} - {(exp.EndDate?.ToString("MMM yyyy") ?? "Present")}")
                                                .FontSize(9).FontColor(Colors.Grey.Darken1);
                                        });
                                        if (!string.IsNullOrEmpty(exp.Description))
                                        {
                                            item.Item().PaddingTop(5).Text(exp.Description).FontSize(9).FontColor(Colors.Grey.Darken2).LineHeight(1.4f);
                                        }
                                    });
                                }
                            }));
                        }

                        // Education
                        if (snapshot.Education?.Count > 0)
                        {
                            column.Item().Element(c => RenderSection(c, "🎓 Education", content =>
                            {
                                foreach (var edu in snapshot.Education)
                                {
                                    content.Item().BorderLeft(3).BorderColor(Colors.Cyan.Medium).PaddingLeft(10).PaddingBottom(10).Column(item =>
                                    {
                                        item.Item().Row(row =>
                                        {
                                            row.RelativeItem().Column(left =>
                                            {
                                                var qualification = edu.Qualification ?? "";
                                                if (!string.IsNullOrEmpty(edu.FieldOfStudy))
                                                    qualification += $" in {edu.FieldOfStudy}";
                                                left.Item().Text(qualification).Bold().FontSize(11).FontColor(Colors.Grey.Darken4);
                                                left.Item().Text(edu.SchoolName ?? "").FontSize(10).FontColor(Colors.Grey.Darken1);
                                            });
                                            row.AutoItem().AlignRight().Background(Colors.Grey.Lighten3).Padding(4)
                                                .Text($"{edu.StartYear} - {(edu.EndYear?.ToString() ?? "Present")}")
                                                .FontSize(9).FontColor(Colors.Grey.Darken1);
                                        });
                                    });
                                }
                            }));
                        }

                        // Skills
                        if (snapshot.Skills?.Count > 0)
                        {
                            column.Item().Element(c => RenderSection(c, "⭐ Skills", content =>
                            {
                                content.Item().Column(skillsColumn =>
                                {
                                    // Create rows of skills (4 per row for better layout)
                                    var skillsList = snapshot.Skills.ToList();
                                    for (int i = 0; i < skillsList.Count; i += 4)
                                    {
                                        skillsColumn.Item().Row(skillRow =>
                                        {
                                            for (int j = i; j < Math.Min(i + 4, skillsList.Count); j++)
                                            {
                                                var skill = skillsList[j];
                                                var (bgColor, textColor) = GetSkillColors(skill.SkillLevel);
                                                skillRow.AutoItem().Padding(2).Background(bgColor).Border(1).BorderColor(bgColor)
                                                    .Padding(5).Row(badge =>
                                                    {
                                                        badge.AutoItem().Text(skill.SkillName ?? "").FontSize(9).FontColor(textColor);
                                                        badge.AutoItem().PaddingLeft(4).Text($"({skill.SkillLevel})").FontSize(8).FontColor(textColor);
                                                    });
                                            }
                                        });
                                    }
                                });
                            }));
                        }

                        // Footer
                        column.Item().Height(20);
                        column.Item().BorderTop(1).BorderColor(Colors.Grey.Lighten2).PaddingTop(10).AlignCenter()
                            .Text($"Generated on {snapshot.GeneratedAt:MMMM dd, yyyy}").FontSize(8).FontColor(Colors.Grey.Medium);
                    });
                });
            });

            using var stream = new MemoryStream();
            document.GeneratePdf(stream);
            return stream.ToArray();
        }

        /// <summary>
        /// Render a section with title and content
        /// </summary>
        private void RenderSection(IContainer container, string title, Action<ColumnDescriptor> contentAction)
        {
            container.PaddingBottom(15).Column(section =>
            {
                section.Item().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).PaddingBottom(5)
                    .Text(title).FontSize(12).Bold().FontColor(Colors.Blue.Medium);
                section.Item().Height(10);
                section.Item().Column(contentAction);
            });
        }

        /// <summary>
        /// Get skill badge colors based on level
        /// </summary>
        private (string bgColor, string textColor) GetSkillColors(string? level)
        {
            return level?.ToLower() switch
            {
                "expert" => (Colors.Green.Lighten4, Colors.Green.Darken3),
                "advanced" => (Colors.Blue.Lighten4, Colors.Blue.Darken3),
                "intermediate" => (Colors.Cyan.Lighten4, Colors.Cyan.Darken3),
                _ => (Colors.Grey.Lighten3, Colors.Grey.Darken2)
            };
        }

        /// <summary>
        /// Get absolute path for profile photo
        /// </summary>
        private string GetAbsolutePhotoPath(string photoPath)
        {
            if (string.IsNullOrEmpty(photoPath))
                return string.Empty;

            // If it's already an absolute path, return it
            if (Path.IsPathRooted(photoPath))
                return photoPath;

            // If it starts with /, it's a web path - convert to file path
            if (photoPath.StartsWith("/"))
            {
                var relativePath = photoPath.TrimStart('/').Replace('/', Path.DirectorySeparatorChar);
                return Path.Combine(_environment.WebRootPath, relativePath);
            }

            // Otherwise, assume it's relative to wwwroot
            return Path.Combine(_environment.WebRootPath, photoPath.Replace('/', Path.DirectorySeparatorChar));
        }

